export default function Sidebar({ active, onNavigate, open }) {
  const [showLogoutModal, setShowLogoutModal] = useState(false);
  const { t } = useContext(LangContext);

  const NAV_ITEMS = [
    { id: 'overview', label: t.dashboard, icon: <Icons.Dashboard /> },
    { id: 'spaces', label: t.spaces, icon: <Icons.ParkingSpace /> },
    { id: 'reports', label: t.reports, icon: <Icons.Reports /> },
    { id: 'payments', label: t.payments, icon: <Icons.Payment /> },
    { id: 'reservations', label: t.reservations, icon: <Icons.Reservation /> },
    { id: 'pricing', label: t.pricing, icon: <Icons.Pressing /> },
    { id: 'access', label: t.access, icon: <Icons.AccessControl /> },
    { id: 'messaging', label: t.messaging, icon: <Icons.Messaging /> },
    { id: 'notifications', label: t.notifications || 'Notifications', icon: <Icons.Notifications /> },
    { id: 'settings', label: t.settings, icon: <Icons.Settings /> },
  ];

  return (
    <>
      <div className={`${s.sidebar} ${open ? s.open : ''}`}>
        <nav className={s.nav}>
          {NAV_ITEMS.map((item) => (
            <button
              key={item.id}
              className={`${s.navItem} ${active === item.id ? s.active : ''}`}
              onClick={() => onNavigate(item.id)}
            >
              <span className={s.navIcon}>{item.icon}</span>
              <span className={s.navLabel}>{item.label}</span>
            </button>
          ))}
        </nav>

        <div className={s.bottomBlock}>
          <button className={s.logout} onClick={() => setShowLogoutModal(true)}>
            <span className={s.logoutIcon}><Icons.LogOut /></span>
            <span className={s.navLabel}>Log Out</span>
          </button>
        </div>
      </div>

      {showLogoutModal && (
        <div className={s.overlayModal}>
          <div className={s.modal}>
            <h3>Sign out of your account?</h3>
            <p>You will need to sign in again to access your dashboard.</p>
            <div className={s.modalActions}>
              <button className={s.cancelBtn} onClick={() => setShowLogoutModal(false)}>Cancel</button>
              <button className={s.confirmLogout} onClick={() => {
                localStorage.removeItem("gariha_token");
                sessionStorage.clear();
                document.cookie.split(";").forEach((c) => {
                  document.cookie = c.replace(/^ +/, "").replace(/=.*/, "=;expires=" + new Date().toUTCString() + ";path=/");
                });
                window.location.replace('/auth');
              }}>
                Sign Out
              </button>
            </div>
          </div>
        </div>
      )}
    </>
  );
}
